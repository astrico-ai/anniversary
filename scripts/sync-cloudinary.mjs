#!/usr/bin/env node
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");

function loadEnv() {
  const env = { ...process.env };
  try {
    const txt = readFileSync(resolve(ROOT, ".env.local"), "utf8");
    for (const line of txt.split("\n")) {
      const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
      if (m) env[m[1]] = m[2].replace(/^["']|["']$/g, "");
    }
  } catch {}
  return env;
}

const env = loadEnv();
const CLOUD = env.NEXT_PUBLIC_CLOUDINARY_CLOUD_NAME;
const KEY = env.CLOUDINARY_API_KEY;
const SECRET = env.CLOUDINARY_API_SECRET;

if (!CLOUD || !KEY || !SECRET) {
  console.error(
    "Missing one of NEXT_PUBLIC_CLOUDINARY_CLOUD_NAME / CLOUDINARY_API_KEY / CLOUDINARY_API_SECRET in .env.local",
  );
  process.exit(1);
}

const auth = "Basic " + Buffer.from(`${KEY}:${SECRET}`).toString("base64");

async function listAll(resourceType) {
  const out = [];
  let nextCursor = null;
  do {
    const url = new URL(
      `https://api.cloudinary.com/v1_1/${CLOUD}/resources/${resourceType}`,
    );
    url.searchParams.set("max_results", "500");
    if (nextCursor) url.searchParams.set("next_cursor", nextCursor);
    const res = await fetch(url, { headers: { Authorization: auth } });
    if (!res.ok) {
      throw new Error(
        `Cloudinary ${resourceType} list failed: ${res.status} ${await res.text()}`,
      );
    }
    const data = await res.json();
    for (const r of data.resources ?? []) {
      out.push({
        publicId: r.public_id,
        folder: r.asset_folder ?? r.folder ?? "",
        type: r.resource_type === "video" ? "video" : "image",
        width: r.width ?? null,
        height: r.height ?? null,
        bytes: r.bytes ?? null,
        createdAt: r.created_at ?? null,
      });
    }
    nextCursor = data.next_cursor ?? null;
  } while (nextCursor);
  return out;
}

console.log("Fetching from Cloudinary...");
const images = await listAll("image");
const videos = await listAll("video");
const all = [...images, ...videos].sort((a, b) =>
  (a.createdAt ?? "").localeCompare(b.createdAt ?? ""),
);

const folders = {};
for (const a of all) {
  const f = a.folder || "_root";
  (folders[f] ??= []).push(a);
}

const folderNames = Object.keys(folders).sort();
console.log(
  `Found ${all.length} assets across ${folderNames.length} folder(s):`,
);
for (const f of folderNames) {
  const items = folders[f];
  const v = items.filter((i) => i.type === "video").length;
  const p = items.length - v;
  console.log(`  ${f.padEnd(28)} — ${p} photo${p === 1 ? "" : "s"}, ${v} video${v === 1 ? "" : "s"}`);
}

const outPath = resolve(ROOT, "src/data/cloudinary-assets.ts");
mkdirSync(dirname(outPath), { recursive: true });
const content = `// AUTO-GENERATED by scripts/sync-cloudinary.mjs — do not edit by hand.
// Run \`npm run sync\` to refresh.

export type CldAsset = {
  publicId: string;
  folder: string;
  type: "image" | "video";
  width: number | null;
  height: number | null;
  bytes: number | null;
  createdAt: string | null;
};

export const cldAssets: CldAsset[] = ${JSON.stringify(all, null, 2)};

export const cldByFolder: Record<string, CldAsset[]> = ${JSON.stringify(folders, null, 2)};

export function assetsInFolder(folder: string): CldAsset[] {
  return cldByFolder[folder] ?? [];
}
`;

writeFileSync(outPath, content);
console.log(`\nWrote ${outPath}`);
